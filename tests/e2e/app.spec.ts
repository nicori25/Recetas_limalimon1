import { test, expect } from '@playwright/test'
async function demo(page: import('@playwright/test').Page) {
  await page.goto('/#/cuenta')
  await page.getByRole('button', { name: 'Entrar a la demo' }).click()
  await expect(page.getByRole('heading', { name: /¿Qué cocinamos hoy/ })).toBeVisible()
}
test('catálogo, filtros combinables y estado vacío', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.recipe-card')).toHaveCount(6)
  await page.getByRole('searchbox').fill('budin')
  await expect(page.locator('.recipe-card')).toHaveCount(1)
  await page.getByRole('searchbox').fill('')
  await page.getByRole('button', { name: 'vegano', exact: true }).click()
  await page.getByRole('button', { name: 'sin gluten', exact: true }).click()
  await expect(page.locator('.recipe-card')).toHaveCount(3)
  await page.getByRole('searchbox').fill('chocolate')
  await expect(page.getByText('No encontramos recetas con estos filtros.')).toBeVisible()
  await page.getByRole('button', { name: 'Ver todas las recetas' }).click()
  await expect(page.locator('.recipe-card')).toHaveCount(6)
})
test('favoritos, comentarios, valoración, compras y cocina persisten', async ({ page }) => {
  await demo(page)
  await page.goto('/#/receta/ensalada-primavera')
  await page.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Guardada' })).toBeVisible()
  await page.getByRole('button', { name: 'Valorar con 4 estrellas' }).click()
  await expect(page.locator('.detail-meta')).toContainText('4.5')
  await page
    .getByLabel('Compartí tu experiencia')
    .fill('¡La hice con lo que tenía y salió buenísima!')
  await page.getByRole('button', { name: 'Publicar comentario' }).click()
  await expect(page.locator('.comment')).toContainText('salió buenísima')
  await page.getByRole('button', { name: 'A mi lista de compras' }).click()
  await page.getByRole('button', { name: 'Modo cocina' }).click()
  await expect(page.getByRole('dialog')).toContainText('PASO 1 DE 3')
  await page.getByRole('button', { name: 'Siguiente' }).click()
  await expect(page.getByRole('dialog')).toContainText('PASO 2 DE 3')
  await page.getByRole('button', { name: 'Salir del modo cocina' }).click()
  await page.goto('/#/compras')
  await expect(page.getByText('7 ingredientes pendientes')).toBeVisible()
  await page.getByRole('checkbox').first().check()
  await page.reload()
  await expect(page.getByRole('checkbox').first()).toBeChecked()
  await page.goto('/#/favoritos')
  await expect(page.locator('.recipe-card')).toHaveCount(1)
  await page.reload()
  await expect(page.locator('.recipe-card')).toHaveCount(1)
})
test('crear, editar y eliminar una receta propia', async ({ page }) => {
  await demo(page)
  await page.goto('/#/publicar')
  await page.getByLabel('Nombre de tu receta').fill('Tarta de la huerta')
  await page.getByLabel('Contanos un poquito').fill('Una receta fácil para compartir en familia.')
  await page.getByLabel('Ingredientes Uno por línea').fill('2 zanahorias\n1 masa de tarta')
  await page
    .getByLabel('Paso a paso')
    .fill('Lavá y cortá las verduras.\nHorneá la tarta por 30 minutos.')
  await page.getByLabel('vegetariano', { exact: true }).check()
  await page.getByRole('button', { name: 'Publicar receta' }).click()
  await expect(page.getByRole('heading', { name: 'Tarta de la huerta', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Editar receta', exact: true }).click()
  await page.getByLabel('Nombre de tu receta').fill('Tarta de zanahorias')
  await page.getByRole('button', { name: 'Guardar cambios' }).click()
  await expect(
    page.getByRole('heading', { name: 'Tarta de zanahorias', exact: true }),
  ).toBeVisible()
  await page.getByRole('button', { name: 'Eliminar receta', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Eliminar receta' }).click()
  await expect(page).toHaveURL(/#\/$/)
  await page.goto('/#/mis-recetas')
  await expect(page.locator('.recipe-card')).toHaveCount(0)
})
test('ruleta respeta los filtros, perfil y administración', async ({ page }) => {
  await demo(page)
  await page.goto('/#/ruleta')
  await page.getByLabel('Temporada').selectOption('primavera')
  await page.getByLabel('Tu preferencia').selectOption('sin gluten')
  await page.getByRole('button', { name: 'Girar la ruleta' }).click()
  await expect(page.locator('.roulette-result .recipe-card')).toBeVisible()
  await page.goto('/#/cuenta')
  await page.getByLabel('Cómo te llamamos').fill('Cocinera de prueba')
  await page.getByRole('button', { name: 'Guardar perfil' }).click()
  await expect(page.getByRole('heading', { name: '¡Hola, Cocinera de prueba!' })).toBeVisible()
  await page.goto('/#/admin')
  await page.getByRole('button', { name: 'Usuarios', exact: true }).click()
  await expect(page.locator('tbody tr')).toHaveCount(2)
  await page.getByRole('button', { name: 'Desactivar Comunidad LimaLimón' }).click()
  await page.getByRole('button', { name: 'Confirmar', exact: true }).click()
  await expect(page.locator('tbody')).toContainText('Desactivado')
})
test('visitante no puede publicar y móvil no desborda', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.locator('.recipe-card')).toHaveCount(6)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(
    true,
  )
  await page.getByRole('button', { name: 'Abrir menú' }).click()
  await expect(page.getByRole('navigation')).toBeVisible()
  await page.getByRole('link', { name: 'Favoritos', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Ingresar', exact: true })).toBeVisible()
  await page.goto('/#/publicar')
  await expect(page.getByRole('heading', { name: 'Tu receta merece ser compartida' })).toBeVisible()
  await page.goto('/#/no-existe')
  await expect(
    page.getByRole('heading', { name: 'Esta página no está en el recetario.' }),
  ).toBeVisible()
})
